    #[test]
    fn field_order_follows_canonical_order() {
        let json = serialize_spaces_record(&base_record());
        let order = top_level_key_order(&json);
        let expected: Vec<&str> = SPACES_FIELDS
            .iter()
            .copied()
            .filter(|f| !matches!(*f, "invitedBy" | "serverInvitationId"))
            .collect();
        assert_eq!(order, expected);
    }

    /// Key order as written in the raw JSON text (serde_json without
    /// `preserve_order` sorts parsed maps alphabetically, so the order must
    /// be read from the text itself).
    fn top_level_key_order(json: &str) -> Vec<String> {
        let chars: Vec<char> = json.chars().collect();
        let mut keys = Vec::new();
        let mut depth = 0i32;
        let mut i = 0usize;
        while i < chars.len() {
            let c = chars[i];
            if c == '"' {
                // Find the closing quote (handles escapes) and check
                // whether this string is a key: the next non-whitespace
                // char after it must be ':' at depth 1.
                let start = i;
                i += 1;
                while i < chars.len() {
                    if chars[i] == '\\' {
                        i += 2;
                        continue;
                    }
                    if chars[i] == '"' {
                        break;
                    }
                    i += 1;
                }
                let mut j = i + 1;
                while j < chars.len() && chars[j].is_whitespace() {
                    j += 1;
                }
                if depth == 1 && j < chars.len() && chars[j] == ':' {
                    let raw: String = chars[start + 1..i].iter().collect();
                    keys.push(raw);
                }
                i += 1;
                continue;
            }
            match c {
                '{' | '[' => depth += 1,
                '}' | ']' => depth -= 1,
                _ => {}
            }
            i += 1;
        }
        keys
    }

